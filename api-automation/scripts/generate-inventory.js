#!/usr/bin/env node
// scripts/generate-inventory.js
//
// Phase 2 of the execution strategy: build the API inventory / coverage
// matrix straight from the OpenAPI spec — nothing here is hand-maintained.
// Run: npm run inventory
// Outputs:
//   reports/inventory.json          — full machine-readable EndpointDescriptor[]
//   reports/coverage-matrix.md      — human-readable per-endpoint matrix

import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildInventory, groupByTag, requiresAuth, securitySchemeName } from "../src/core/specLoader.js";
import { flattenFields } from "../src/core/schemaUtils.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPORTS_DIR = path.resolve(__dirname, "../reports");
mkdirSync(REPORTS_DIR, { recursive: true });

const inventory = buildInventory();

// ---- reports/inventory.json --------------------------------------------
writeFileSync(path.join(REPORTS_DIR, "inventory.json"), JSON.stringify(inventory, null, 2));

// ---- reports/coverage-matrix.md ----------------------------------------
const grouped = groupByTag(inventory);
const tags = [...grouped.keys()].sort();

let totalParams = 0;
let totalBodyFields = 0;
let totalEnumValues = 0;
let totalStatusCodes = 0;
let authedEndpoints = 0;

const rows = [];
for (const tag of tags) {
  for (const ep of grouped.get(tag)) {
    const bodyFields = ep.requestBody?.schema ? flattenFields(ep.requestBody.schema) : [];
    const enumCount = bodyFields.reduce((s, f) => s + (f.enum?.length || 0), 0);
    const statusCodes = Object.keys(ep.responses);
    const auth = requiresAuth(ep);

    totalParams += ep.parameters.length;
    totalBodyFields += bodyFields.length;
    totalEnumValues += enumCount;
    totalStatusCodes += statusCodes.length;
    if (auth) authedEndpoints += 1;

    rows.push({
      tag,
      method: ep.method.toUpperCase(),
      path: ep.path,
      auth: auth ? securitySchemeName(ep) : "none",
      params: ep.parameters.length,
      bodyFields: bodyFields.length,
      enums: enumCount,
      statuses: statusCodes.join(", "),
    });
  }
}

const header =
  "| Module | Method | Endpoint | Auth | Params | Body Fields | Enum Values | Documented Statuses |\n" +
  "|---|---|---|---|---|---|---|---|\n";

const body = rows
  .map(
    (r) =>
      `| ${r.tag} | ${r.method} | \`${r.path}\` | ${r.auth} | ${r.params} | ${r.bodyFields} | ${r.enums} | ${r.statuses} |`
  )
  .join("\n");

const summary =
  `# VMS API Coverage Matrix\n\n` +
  `Auto-generated from \`spec/vms-openapi.json\` by \`npm run inventory\`. Do not edit by hand — re-run the script after the spec changes.\n\n` +
  `## Summary\n\n` +
  `- Total endpoints (method + path): **${inventory.length}**\n` +
  `- Tags/modules: **${tags.length}**\n` +
  `- Endpoints requiring authentication: **${authedEndpoints}** / ${inventory.length}\n` +
  `- Total documented parameters (path+query): **${totalParams}**\n` +
  `- Total request-body fields (incl. nested): **${totalBodyFields}**\n` +
  `- Total enum values across all bodies: **${totalEnumValues}**\n` +
  `- Total documented response status codes (sum across endpoints): **${totalStatusCodes}**\n\n` +
  `See \`reports/coverage-report.md\` (generated by \`npm run coverage\` after a test run) for which of these are ACTUALLY exercised by the automation, vs. still outstanding.\n\n` +
  `## Per-endpoint matrix\n\n${header}${body}\n`;

writeFileSync(path.join(REPORTS_DIR, "coverage-matrix.md"), summary);

console.log(`Inventory built: ${inventory.length} endpoints across ${tags.length} tags.`);
console.log(`  -> reports/inventory.json`);
console.log(`  -> reports/coverage-matrix.md`);
